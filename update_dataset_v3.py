# Auto-generate title for any items without a custom one
def generate_title(item):
    item_id = item["id"]
    if item_id in custom_titles:
        return custom_titles[item_id]
    
    q = item["question"].strip()
    core = item["core_prediction"].strip()
    
    # Strip prefixes like 问：
    q_clean = re.sub(r"^(问[：:]|\d+\.\s*)", "", q)
    # Take first sentence or up to 16 chars
    first_part = re.split(r"[，。？！,\?!]", q_clean)[0].strip()
    if 4 <= len(first_part) <= 15:
        return first_part
    
    # Try core prediction
    core_clean = re.sub(r"^(【[^】]+】|自称|指出|强调|预测)", "", core).strip()
    core_part = re.split(r"[，。？！,\?!]", core_clean)[0].strip()
    if 4 <= len(core_part) <= 16:
        return core_part
        
    return q_clean[:14]

